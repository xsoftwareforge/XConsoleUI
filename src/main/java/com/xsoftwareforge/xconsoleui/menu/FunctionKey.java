package com.xsoftwareforge.xconsoleui.menu;

/**
 * The function keys F1-F12 that a {@link Menu} or {@link MenuRegistry} can bind to
 * a {@link Hotkey} action. Decoupled from the terminal layer so consumers never
 * touch screen internals.
 */
public enum FunctionKey {
    F1, F2, F3, F4, F5, F6, F7, F8, F9, F10, F11, F12
}
